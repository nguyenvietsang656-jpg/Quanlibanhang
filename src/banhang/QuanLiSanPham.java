    private void btnThemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemActionPerformed
        String maSP = txtMaSP.getText().trim();
        String tenSP = txtTenSP.getText().trim();
        String dvt = txtDVT.getText().trim();
        String donGiaStr = txtDonGia.getText().trim();
        String soLuongStr = txtSoLuong.getText().trim();
        
        if (maSP.isEmpty() || tenSP.isEmpty() || dvt.isEmpty() || donGiaStr.isEmpty() || soLuongStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập đầy đủ thông tin!");
            return;
        }
        
        try {
            Connection conn = Ketnoi.getConnection();
            String sql = "INSERT INTO SanPham (MaSP, TenSP, DonViTinh, DonGia, SoLuongTon) VALUES (?, ?, ?, ?, ?)";
            PreparedStatement pstmt = conn.prepareStatement(sql);
            pstmt.setString(1, maSP);
            pstmt.setString(2, tenSP);
            pstmt.setString(3, dvt);
            pstmt.setDouble(4, Double.parseDouble(donGiaStr));
            pstmt.setInt(5, Integer.parseInt(soLuongStr));
            
            int rowsInserted = pstmt.executeUpdate();
            if (rowsInserted > 0) {
                JOptionPane.showMessageDialog(this, "Thêm sản phẩm thành công!");
                DuLieuBang(); 
                LamMoi();
            }
            pstmt.close();
            conn.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Lỗi thêm (Trùng mã SP hoặc sai kiểu dữ liệu): " + e.getMessage());
        }
    }//GEN-LAST:event_btnThemActionPerformed

    private void btnSuaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSuaActionPerformed
        String maSP = txtMaSP.getText().trim();
        String tenSP = txtTenSP.getText().trim();
        String dvt = txtDVT.getText().trim();
        String donGiaStr = txtDonGia.getText().trim();
        String soLuongStr = txtSoLuong.getText().trim();
        
        if (maSP.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn sản phẩm hoặc nhập Mã SP cần sửa!");
            return;
        }
        
        try {
            Connection conn = Ketnoi.getConnection();
            // Cập nhật thông tin dựa vào Mã SP (MaSP là khóa chính nên dùng làm điều kiện WHERE)
            String sql = "UPDATE SanPham SET TenSP = ?, DonViTinh = ?, DonGia = ?, SoLuongTon = ? WHERE MaSP = ?";
            PreparedStatement pstmt = conn.prepareStatement(sql);
            pstmt.setString(1, tenSP);
            pstmt.setString(2, dvt);
            pstmt.setDouble(3, Double.parseDouble(donGiaStr));
            pstmt.setInt(4, Integer.parseInt(soLuongStr));
            pstmt.setString(5, maSP);
            
            int rowsUpdated = pstmt.executeUpdate();
            if (rowsUpdated > 0) {
                JOptionPane.showMessageDialog(this, "Cập nhật sản phẩm thành công!");
                DuLieuBang();
                LamMoi();
            } else {
                JOptionPane.showMessageDialog(this, "Không tìm thấy Mã SP cần sửa!");
            }
            pstmt.close();
            conn.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Lỗi sửa dữ liệu: " + e.getMessage());
        }
    }//GEN-LAST:event_btnSuaActionPerformed

    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed
        String maSP = txtMaSP.getText().trim();
        
        if (maSP.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn sản phẩm cần xóa trên bảng!");
            return;
        }
        
        int confirm = JOptionPane.showConfirmDialog(this, "Bạn có chắc chắn muốn xóa sản phẩm này?", "Xác nhận xóa", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            try {
                Connection conn = Ketnoi.getConnection();
                String sql = "DELETE FROM SanPham WHERE MaSP = ?";
                PreparedStatement pstmt = conn.prepareStatement(sql);
                pstmt.setString(1, maSP);
                
                int rowsDeleted = pstmt.executeUpdate();
                if (rowsDeleted > 0) {
                    JOptionPane.showMessageDialog(this, "Xóa sản phẩm thành công!");
                    DuLieuBang(); // Cập nhật lại bảng
                    LamMoi();
                }
                pstmt.close();
                conn.close();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Lỗi xóa dữ liệu: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnXoaActionPerformed

    private void tblGioHangMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblGioHangMouseClicked
        int row = tblGioHang.getSelectedRow();
        if (row >= 0) {
            DefaultTableModel model = (DefaultTableModel) tblGioHang.getModel();
            txtMaSP.setText(model.getValueAt(row, 0).toString());
            txtTenSP.setText(model.getValueAt(row, 1).toString());
            txtDVT.setText(model.getValueAt(row, 2).toString());
            txtDonGia.setText(model.getValueAt(row, 3).toString());
            txtSoLuong.setText(model.getValueAt(row, 4).toString());
            
            // Khóa ô Mã SP lại khi sửa để tránh người dùng sửa đổi khóa chính gây lỗi
            txtMaSP.setEditable(false); 
        }
    }//GEN-LAST:event_tblGioHangMouseClicked

