private void themSanPhamVaoBang() {

    String maSP = txtMaSP.getText().trim();

    if (maSP.isEmpty()) {
        return;
    }

    String sql = "SELECT MaSP, TenSP, DonViTinh, DonGia, SoLuongTon "
               + "FROM SanPham WHERE MaSP = ?";

    try {
        Connection conn = Ketnoi.getConnection();
        PreparedStatement ps = conn.prepareStatement(sql);

        ps.setString(1, maSP);

        ResultSet rs = ps.executeQuery();

        if (rs.next()) {

            double donGia = rs.getDouble("DonGia");
            int tonKho = rs.getInt("SoLuongTon");
            int soLuong = 1;


            model.addRow(new Object[]{
              rs.getString("MaSP"),
              rs.getString("TenSP"),
              rs.getString("DonViTinh"),
              donGia,
              tonKho,
              soLuong
            });
            tinhTongTien();
            txtMaSP.setText("");
            txtMaSP.requestFocus();

        } else {

            JOptionPane.showMessageDialog(this,
                    "Không tìm thấy mã sản phẩm: " + maSP);
        }

        rs.close();
        ps.close();
        conn.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
                "Lỗi: " + e.getMessage());
    }
}
