   private void tinhTongTien() {

    double tong = 0;

    for (int i = 0; i < tblGioHang.getRowCount(); i++) {

        double donGia = Double.parseDouble(
                tblGioHang.getValueAt(i, 3).toString()
        );

        int soLuong = Integer.parseInt(
                tblGioHang.getValueAt(i, 5).toString()
        );

        double thanhTien = donGia * soLuong;

        tong += thanhTien;
    }

    txtTongTien.setText(
            String.format("%,.0f", tong)
    );
}
   private void capNhapTien() {

    if (dangCapNhat) {
        return;
    }

    dangCapNhat = true;

    try {

        for (int i = 0; i < tblGioHang.getRowCount(); i++) {

            // Cột 3 = Đơn giá
            double donGia = Double.parseDouble(
                    tblGioHang.getValueAt(i, 3).toString()
            );

            // Cột 4 = Số lượng tồn
            int tonKho = Integer.parseInt(
                    tblGioHang.getValueAt(i, 4).toString()
            );

            // Cột 5 = Số lượng
            int soLuong;

            try {
                soLuong = Integer.parseInt(
                        tblGioHang.getValueAt(i, 5).toString()
                );
            } catch (Exception e) {
                soLuong = 1;
            }

            if (soLuong <= 0) {
                soLuong = 1;
            }

            if (soLuong > tonKho) {

                JOptionPane.showMessageDialog(this,
                        "Số lượng không được vượt quá tồn kho!");

                soLuong = tonKho;
            }

            // Cập nhật lại số lượng
            tblGioHang.setValueAt(soLuong, i, 5);
        }

        // Tính lại tổng tiền
        tinhTongTien();

    } finally {
        dangCapNhat = false;
    }
}
