    private void TableHoaDon() {
        modelHoaDon.setRowCount(0);
        String sql = "SELECT MaHD, NgayLap, TongTien FROM HoaDon ORDER BY NgayLap DESC";

        try (Connection conn = Ketnoi.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {

            while (rs.next()) {
                String maHD = rs.getString("MaHD");
                String ngayLap = rs.getString("NgayLap");
                int tongTien = rs.getInt("TongTien");

                modelHoaDon.addRow(new Object[]{
                    maHD, ngayLap, String.format("%,d VNĐ", tongTien)
                });
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Lỗi tải lịch sử hóa đơn: " + e.getMessage());
        }
    }

    
    private void ChiTietHoaDon(String maHD) {
        modelChiTiet.setRowCount(0);
        String sql = "SELECT c.MaSP, s.TenSP, c.SoLuong, c.DonGia "
                   + "FROM ChiTietHoaDon c "
                   + "JOIN SanPham s ON c.MaSP = s.MaSP "
                   + "WHERE c.MaHD = ?";

        try (Connection conn = Ketnoi.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {

            ps.setString(1, maHD);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    String maSP = rs.getString("MaSP");
                    String tenSP = rs.getString("TenSP");
                    int soLuong = rs.getInt("SoLuong");
                    int donGia = rs.getInt("DonGia");
                    int thanhTien = soLuong * donGia;

                    modelChiTiet.addRow(new Object[]{
                        maSP, tenSP, soLuong, String.format("%,d", donGia), String.format("%,d", thanhTien)
                    });
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Lỗi tải chi tiết hóa đơn: " + e.getMessage());
        }
    }

